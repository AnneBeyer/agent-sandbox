#!/usr/bin/env bash
# Configure and check SSH access to the remote GPU hosts with the dedicated
# agent key.
#
#   tools/agent_ssh.sh setup   write ~/.ssh/agent-sandbox/config and include it
#   tools/agent_ssh.sh check   report which hosts answer and their GPU usage
#
# Settings come from the environment, or from ~/.config/agent-sandbox/env
# (override with AGENT_SANDBOX_ENV):
#
#   AGENT_SSH_HOSTS     "alias=user@ip ..."  (required)
#   AGENT_SSH_JUMP      "user@host[:port]"   (optional jump host)
#   AGENT_SSH_KEY_FILE  private key path, default ~/.ssh/agent_sandbox_ed25519
#   AGENT_SSH_KEY       private key contents (runners); written to
#                       ~/.ssh/agent-sandbox/id_ed25519 and used instead
set -euo pipefail

env_file="${AGENT_SANDBOX_ENV:-$HOME/.config/agent-sandbox/env}"
if [[ -f "$env_file" ]]; then
    # shellcheck disable=SC1090
    source "$env_file"
fi

conf_dir="$HOME/.ssh/agent-sandbox"
conf_file="$conf_dir/config"

die() {
    echo "agent_ssh: $*" >&2
    exit 1
}

# Print "user host port" for a "user@host[:port]" spec.
split_target() {
    local spec="$1" user host port
    [[ "$spec" == *@* ]] || die "expected user@host, got '$spec'"
    user="${spec%%@*}"
    host="${spec#*@}"
    port=22
    if [[ "$host" == *:* ]]; then
        port="${host##*:}"
        host="${host%:*}"
    fi
    echo "$user $host $port"
}

key_path() {
    if [[ -n "${AGENT_SSH_KEY:-}" ]]; then
        echo "$conf_dir/id_ed25519"
    else
        local key="${AGENT_SSH_KEY_FILE:-$HOME/.ssh/agent_sandbox_ed25519}"
        echo "${key/#\~/$HOME}"
    fi
}

host_block() {
    local alias="$1" user="$2" host="$3" port="$4" key="$5"
    cat <<EOF
Host $alias
    HostName $host
    User $user
    Port $port
    IdentityFile $key
    IdentitiesOnly yes
    BatchMode yes
    ConnectTimeout 15
    ServerAliveInterval 30
    StrictHostKeyChecking accept-new
EOF
}

setup() {
    [[ -n "${AGENT_SSH_HOSTS:-}" ]] || die "AGENT_SSH_HOSTS is not set (see README.md)"
    mkdir -p "$conf_dir"
    chmod 700 "$HOME/.ssh" "$conf_dir"

    local key
    key="$(key_path)"
    if [[ -n "${AGENT_SSH_KEY:-}" ]]; then
        (umask 077 && printf '%s\n' "$AGENT_SSH_KEY" >"$key")
    fi
    [[ -f "$key" ]] || die "private key not found at $key"

    local tmp
    tmp="$(mktemp)"
    echo "# Generated by tools/agent_ssh.sh, do not edit." >"$tmp"
    local jump=""
    if [[ -n "${AGENT_SSH_JUMP:-}" ]]; then
        read -r user host port <<<"$(split_target "$AGENT_SSH_JUMP")"
        host_block agent-jump "$user" "$host" "$port" "$key" >>"$tmp"
        jump=agent-jump
    fi
    local entry name
    for entry in $AGENT_SSH_HOSTS; do
        [[ "$entry" == *=* ]] || die "expected alias=user@ip in AGENT_SSH_HOSTS, got '$entry'"
        name="${entry%%=*}"
        read -r user host port <<<"$(split_target "${entry#*=}")"
        host_block "agent-$name" "$user" "$host" "$port" "$key" >>"$tmp"
        if [[ -n "$jump" ]]; then
            echo "    ProxyJump $jump" >>"$tmp"
        fi
    done
    mv "$tmp" "$conf_file"
    chmod 600 "$conf_file"

    # Include must come before any Host block in ~/.ssh/config to apply.
    local include="Include $conf_file"
    local user_conf="$HOME/.ssh/config"
    if ! grep -qxF "$include" "$user_conf" 2>/dev/null; then
        if [[ -f "$user_conf" ]]; then
            cp "$user_conf" "$user_conf.bak-agent-sandbox"
            { echo "$include"; echo; cat "$user_conf.bak-agent-sandbox"; } >"$user_conf"
        else
            echo "$include" >"$user_conf"
        fi
        chmod 600 "$user_conf"
    fi

    echo "Wrote $conf_file with hosts:"
    grep '^Host agent-' "$conf_file" | sed 's/^Host /  /'
}

check() {
    [[ -f "$conf_file" ]] || die "run '$0 setup' first"
    local alias
    while read -r alias; do
        echo "== $alias"
        ssh -n "$alias" 'hostname; nvidia-smi --query-gpu=name,memory.used,memory.total,utilization.gpu --format=csv,noheader 2>/dev/null || echo "no nvidia-smi"; free -g | head -2' \
            || echo "unreachable (host may be shut down; ask the operator)"
    done < <(awk '/^Host agent-/ && $2 != "agent-jump" {print $2}' "$conf_file")
}

case "${1:-}" in
    setup) setup ;;
    check) check ;;
    *) echo "usage: $0 setup|check" >&2; exit 2 ;;
esac
